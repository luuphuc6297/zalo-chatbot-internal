#!/usr/bin/env python3
"""Build the small menu thumbnails the staff console shows (task C), as a generated TypeScript module.

  python3 -I scripts/build_menu_thumbs.py [--check] [--quiet]

The Worker cannot read files at runtime, so the thumbnails are bundled: for every slide of data/menu-images.json that
staff or the bot can send (a cover, a price list or a slide of a service), macOS `sips` makes a JPEG with the long side
at most 320 px and quality 55 from the original slide in sources/drive-resources/, and the script writes them as base64
into apps/server/src/menu-thumbs.ts (about 20 KB per slide). GET /staff/menu-images/:group/:n serves them
(src/staff-api/menu.ts). The bridge never uses these files; it sends the full JPEGs of scripts/build_menu_images.py.

Idempotent: the module is rewritten only when its content changes. Exit codes: 0 up to date (or written), 1 --check
found the module out of date, 2 cannot build (no sips, index unreadable, a slide failed). Output names counts only.
Run it again after data/menu-images.json or a slide image changes, then restart the server.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "data" / "menu-images.json"
OUT = ROOT / "apps" / "server" / "src" / "menu-thumbs.ts"
LONG_SIDE = 320
QUALITY = 55
KEY_RE = re.compile(r"^(facial|healing|thu-gian-toc|hair-removal)/([1-9][0-9]?)$")
SIPS_TIMEOUT_S = 60


def sendable_keys(index: dict) -> list[str]:
    """Keys reachable by attach_menu_images or the console: covers, price lists and the slides of each service."""
    keys: set[str] = set()
    for group, g in index["groups"].items():
        for n in [*g.get("cover", []), *g.get("price_list", [])]:
            keys.add(f"{group}/{n}")
        for ns in g.get("services", {}).values():
            keys.update(f"{group}/{n}" for n in ns)
        for u in g.get("unmatched_services", []):
            keys.update(f"{group}/{n}" for n in u.get("slides", []))
    known = {s["key"] for s in index["slides"]}
    return sorted(k for k in keys if k in known and KEY_RE.match(k))


def render_module(thumbs: dict[str, str]) -> str:
    digest = hashlib.sha256(json.dumps(thumbs, sort_keys=True).encode()).hexdigest()[:16]
    lines = [
        "// GENERATED by scripts/build_menu_thumbs.py from data/menu-images.json and the slides in",
        "// sources/drive-resources/thomhouse-menu. Do not edit by hand. JPEG thumbnails (long side 320 px), base64.",
        f"export const MENU_THUMBS_VERSION = '{digest}';",
        "export const MENU_THUMBS: Record<string, string> = {",
    ]
    for k in sorted(thumbs, key=lambda x: (x.split("/")[0], int(x.split("/")[1]))):
        lines.append(f"  {json.dumps(k)}: {json.dumps(thumbs[k])},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def make_thumb(sips: str, src: Path, tmp: Path) -> bytes:
    out = tmp / "thumb.jpg"
    subprocess.run(
        [sips, "-Z", str(LONG_SIDE), "-s", "format", "jpeg", "-s", "formatOptions", str(QUALITY), str(src), "--out", str(out)],
        check=True, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=SIPS_TIMEOUT_S,
    )
    data = out.read_bytes()
    out.unlink()
    if not data.startswith(b"\xff\xd8"):
        raise ValueError("sips did not write a JPEG")
    return data


def build(index_path: Path = INDEX, out_path: Path = OUT, check: bool = False, sips: str | None = None) -> int:
    try:
        index = json.loads(index_path.read_text(encoding="utf-8"))
        by_key = {s["key"]: s for s in index["slides"]}
        keys = sendable_keys(index)
    except (OSError, ValueError, KeyError, TypeError) as e:
        print(f"cannot read the slide index: {type(e).__name__}", file=sys.stderr)
        return 2
    sips = sips or shutil.which("sips")
    if not sips:
        print("sips not found (macOS only)", file=sys.stderr)
        return 2
    thumbs: dict[str, str] = {}
    with tempfile.TemporaryDirectory() as tmp:
        for k in keys:
            src = (index_path.parent.parent / by_key[k]["file"]).resolve()
            try:
                thumbs[k] = base64.b64encode(make_thumb(sips, src, Path(tmp))).decode()
            except (OSError, ValueError, subprocess.SubprocessError) as e:
                print(f"slide {k}: {type(e).__name__}", file=sys.stderr)
                return 2
    text = render_module(thumbs)
    current = out_path.read_text(encoding="utf-8") if out_path.exists() else ""
    if current == text:
        return 0
    if check:
        return 1
    out_path.write_text(text, encoding="utf-8")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when the module is out of date; write nothing")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()
    rc = build(check=args.check)
    if not args.quiet and rc == 0:
        print(f"menu thumbnails up to date: {OUT.relative_to(ROOT)}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
