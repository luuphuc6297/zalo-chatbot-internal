// Generates apps/server/src/seed-data.ts from the read-only sources, so the Worker never reads the repo at runtime.
// Run: pnpm -C apps/server gen:seed   (re-run whenever data/*.json, design/system-prompt-draft.md or design/tools-schema.json change)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');

function blockA() {
  const text = read('design/system-prompt-draft.md');
  const start = text.indexOf('## Khối A');
  if (start < 0) throw new Error('"## Khối A" not found in design/system-prompt-draft.md');
  const fence = text.indexOf('```text\n', start);
  if (fence < 0) throw new Error('no ```text fence under Khối A');
  const from = fence + '```text\n'.length;
  const end = text.indexOf('\n```', from);
  return text.slice(from, end).trim();
}

const data = {
  services_json: JSON.parse(read('data/services.json')),
  business_facts_json: JSON.parse(read('data/business-facts.json')),
  block_a: blockA(),
  tools_schema_json: JSON.parse(read('design/tools-schema.json')),
};

const out =
  '// GENERATED by apps/server/scripts/gen-seed-data.mjs from data/services.json, data/business-facts.json,\n' +
  '// design/system-prompt-draft.md (block A) and design/tools-schema.json. Do not edit by hand.\n' +
  "import type { DevSeedRequest } from './types';\n\n" +
  `export const SEED_DATA: Required<Pick<DevSeedRequest, 'services_json' | 'business_facts_json' | 'block_a' | 'tools_schema_json'>> = ${JSON.stringify(data, null, 1)};\n`;
writeFileSync(resolve(here, '../src/seed-data.ts'), out);
console.log(`wrote src/seed-data.ts (${out.length} bytes, block_a ${data.block_a.length} chars)`);
